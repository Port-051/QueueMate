package com.queuemate.matching.domain;

/**
 * 제안에 응답한 결과. 컨트롤러가 이 값으로 HTTP 상태를 정한다.
 *
 * <p>수락과 거절이 <b>한 enum</b>을 쓴다. 갈리는 것은 성공 갈래뿐이고
 * (수락은 {@link #ACCEPTED} / {@link #CONFIRMED}, 거절은 {@link #DECLINED})
 * 거부 갈래는 셋 다 같기 때문이다. 따로 두면 같은 값을 두 벌 관리하게 되고,
 * 컨트롤러의 거부 처리도 두 벌이 된다.
 *
 * <p>응답은 <b>거절될 수 있는 명령</b>이라 결과를 요청자에게 되돌려 줘야 한다.
 * 이미 만료됐거나, 이미 눌렀거나, 참가자가 아닐 수 있다. 알림(Pub/Sub)이 아니라
 * REST 로 받는 이유가 이것이다.
 */
public enum ProposalResult {

    /** 수락이 기록됐다. 아직 전원이 수락하지는 않았다 */
    ACCEPTED,

    /** 내 수락으로 전원이 찼다. 제안이 확정됐다 (INV-4) */
    CONFIRMED,

    /**
     * 제안이 깨졌다.
     *
     * <p>거절에서는 <b>내 거절로 제안을 실제로 깬 한 번</b>만 이 값이다. 같은 거절을 다시
     * 보내면 {@link #NOT_FOUND} 다 — 거절이 파티 HASH 의 제안 흔적을 지우기 때문이다
     * ({@code decline-proposal.lua}). 수락에서는 다른 참가자가 먼저 거절한 경우인데,
     * 같은 이유로 현재 그 경로는 {@link #NOT_FOUND} 로 떨어진다.
     */
    DECLINED,

    /**
     * 내가 이미 수락해 놓고 거절을 눌렀다.
     *
     * <p>재시도가 아니라 진짜 충돌이라 컨트롤러가 409 로 내보낸다. 같은 응답을 두 번 보낸
     * 경우는 여기로 오지 않는다 — 수락 재시도는 {@link #ACCEPTED}/{@link #CONFIRMED},
     * 거절 재시도는 {@link #NOT_FOUND} 다.
     */
    ALREADY_RESPONDED,

    /** 이 제안의 참가자가 아니다 */
    NOT_A_MEMBER,

    /**
     * 그런 제안이 없다.
     *
     * <p>시한이 지나 정리된 경우도, <b>누가 이미 거절해 제안이 지워진 경우</b>(같은 거절의
     * 재시도 포함)도 여기로 온다. 만료된 제안은 sweeper 가 지우므로 "만료됨"과 "깨짐"과
     * "애초에 없음"을 구분할 방법이 없고, 클라이언트가 할 일도 같다 —
     * 대기 화면으로 돌아간다.
     */
    NOT_FOUND
}
