-- 소셜 로그인에서 이메일을 받아 저장한다 — 2026-10-13 소유자 결정(contracts/platform-api.md P-58).
-- 소셜 제공자(카카오 · 디스코드 · 구글)의 사용자 정보에서 "선택 동의"로 받은 이메일을 사용자에게 적는다. 전화번호는 받지 않는다.
--
-- email : 제공자가 준 이메일. 없으면 NULL — 사용자가 동의 항목을 거절했거나(카카오 "선택 동의"), 제공자가 그 칸을 주지 않았거나,
--         제공자가 "검증됨" 이라고 말하지 않은 값이다. **검증된 값만 적는다** — 구글은 email_verified 가 true, 디스코드는 verified 가 true,
--         카카오는 kakao_account.is_email_valid 와 is_email_verified 가 둘 다 true 일 때만. 아니면 NULL 이다(값이 와도 버린다).
--         가입 때 적고, 로그인 · 잇기 때 제공자가 검증된 값을 주면 덮어쓴다 — 나중에 동의해도 채워진다. NULL 로는 덮어쓰지 않는다.
--         **식별자가 아니다** — UNIQUE 가 없다. 같은 이메일로 두 소셜 계정(두 사용자)이 생길 수 있고, 이것으로 사용자를 찾거나 합치지 않는다.
--         식별자는 여전히 users.id 하나다(V1 머리 · CLAUDE.md §3.5). 320 은 RFC 가 허용하는 주소의 최대 길이다.
--         회원 탈퇴(P-48)가 users 의 줄을 지우면 같이 사라진다 — 다른 테이블에 사본이 없다.
--         이메일이 없어도(NULL) 가입 · 로그인은 그대로 된다. 개발용 로그인(TEMP-DEV-LOGIN)은 늘 NULL 이다.
--
-- V1 ~ V12 는 고치지 않는다 — 이미 적용된 파일은 체크섬이 달라져 기동이 막힌다(V1 머리의 약속).
ALTER TABLE users ADD COLUMN email varchar(320);
